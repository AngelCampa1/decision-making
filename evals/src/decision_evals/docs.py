"""Documentation that resolves to something that exists.

Every other integrity rule in this repository has a gate. Documentation was
checked by reading it, and on 2026-08-13 an audit found the front door making
three claims that were false at the time it was read:

- ``README.md`` told the reader to run ``de screen`` and ``de confirm``.
  Neither is a command. ``dev``/``screen``/``confirm`` are an ``Arena`` literal
  in :mod:`decision_evals.arenas`; the runner behind all 2,555 calls of the one
  working instrument is ``scripts/run_triggers.py``.
- ``README.md`` listed a ``preregistration/`` component. There is no such
  directory, and :mod:`decision_evals.prereg` -- the module that would fill it
  -- is the one entry in ``[tool.decision-evals.unwired]``.
- The same table omitted ``paper/`` and ``scripts/``, so the two directories a
  newcomer most needs were the two the map did not show.

``SCORECARD.md`` opens by correcting a fourth of the same shape: it claimed to
be generated by ``de report``, which has never existed. **Four instances, one
file each, none caught by anything.**

So the rule, and the reason it is three narrow checks rather than a
spell-check: a gate that flags prose becomes noise, and noise is what an
advisory gate becomes before somebody turns it off. These three refuse only
references that do not resolve -- a command that is not a command, a path that
is not a path, a component table that disagrees with the directory listing.

**What this cannot catch, stated so nobody mistakes green for correct.** It
reads whether a reference exists, never whether the sentence around it is true.
``docs/PROTOCOL.md`` §3 named ``preregistration/<skill>-v<n>.yaml`` correctly
while describing in the present indicative a refusal that has never run; every
path in it resolved. That defect is invisible here and always will be. The
same standing limitation is registered for
:mod:`decision_evals.provenance` and :mod:`decision_evals.wiring`.

**And a reference can be correct while being unresolvable, which took until
2026-08-19 to notice.** This gate ran on the authoring machine every time, so
"the path exists" meant "exists in the working directory". The first run
against a clean clone found two living documents naming files under
``results/track-0/`` and ``results/triggers/``, both excluded by ``.gitignore``
because an append-only run checkpoint cannot be committed mid-run. The
sentences are true, the files are real, and no reader who clones this
repository will ever see them. :func:`load_ignored_paths` is the register that
lets such a reference stand while declaring the absence, exactly as
``de report`` is declared. It carries one refusal rather than two, and the
asymmetry is explained there.

**Scope is the living documentation only.** ``notebook/`` and the published
``results/**/README.md`` are append-only records of what was true when they
were written -- a notebook entry naming ``de report`` in 2026-08-11 is correct
history, and a gate that demanded it be edited would destroy the evidence the
whole method rests on. They are excluded by :data:`SCANNED`, not by an
exception somebody has to remember.
"""

from __future__ import annotations

import re
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Final

#: The living documentation. Globs relative to the repository root, in the
#: order a reader meets them. ``notebook/`` and ``results/`` are deliberately
#: absent -- see the module docstring.
#:
#: Recursive since 2026-08-21. It was ``docs/*.md`` for eight days, one level
#: deep, so ``docs/reviews/`` and ``docs/superpowers/`` were rendered by the
#: site, linked from ``docs/README.md``, and read by nothing. Widening it found
#: 23 unresolvable references, all of them in one dated plan.
SCANNED: Final[tuple[str, ...]] = ("*.md", "docs/**/*.md")

#: Dated registers caught by :data:`SCANNED` that are records rather than
#: instructions. ``docs/DECISIONS.md`` explains past decisions, and a decision
#: that removed a file necessarily names the file it removed -- the entry for
#: ``8541d46`` names ``datasets/triggers/evidence-ledger.yaml``, which that
#: commit deleted. Demanding an edit there would corrupt the register for the
#: same reason it would corrupt ``notebook/``.
EXCLUDED: Final[frozenset[str]] = frozenset({"docs/DECISIONS.md"})

#: Directories under :data:`SCANNED` that hold records rather than
#: instructions, excluded by prefix. A plan is what somebody intended on the
#: day it is dated, and ``docs/superpowers/plans/`` names files it proposed and
#: never created, a ``skills/evidence-ledger/`` that was later deleted, and
#: line ranges like ``runner.py:211-221`` that moved the next time the file
#: was touched. Each of those is correct history and none of them resolves.
#:
#: Excluded as a class, not as the files that happen to fail today. One plan in
#: that directory is clean, and gating it would make the rule "records are
#: checked until they age", which nobody can write to.
EXCLUDED_PREFIXES: Final[frozenset[str]] = frozenset({"docs/superpowers/plans/"})

#: The documentation index, and the page the site serves at ``/docs/``.
INDEX_PATH: Final = "docs/README.md"

#: The line every living document carries under its title, naming the one
#: audience it serves.
AUDIENCE_MARKER: Final = "**Audience:**"

#: Generated documents, which carry an audience line because their generator
#: writes one. Listed so a reader of this module can see that the rule has no
#: exemptions rather than having to check.
GENERATED: Final[frozenset[str]] = frozenset({"docs/RUN_INDEX.md"})

#: The README section whose table is the map of the repository.
COMPONENT_HEADING: Final = "## What's actually here"

#: Top-level directories a component table is not obliged to list. Dot
#: directories are tooling rather than components and are excluded in
#: :func:`check_component_table` itself; this is for anything else that earns
#: an exemption, and it is empty because nothing has.
UNLISTED_DIRS: Final[frozenset[str]] = frozenset()

#: ``pyproject.toml`` table naming commands that are mentioned while absent.
ABSENT_TABLE: Final[tuple[str, ...]] = ("tool", "decision-evals", "docs-absent-commands")

#: ``pyproject.toml`` table naming backticked paths that belong to a *different*
#: repository. :func:`repo_paths` resolves any fragment whose first segment is a
#: real top-level directory against this root, which is right for the paths this
#: repository documents and wrong for the ones it describes in others:
#: ``docs/DECISION_FRAMEWORKS.md`` reviews a prompt library that keeps twenty
#: files in ``.claude/commands/``, and ``.claude/`` is a directory here, so a
#: true sentence about somebody else's layout was reported as a broken link.
#: Same rules as :data:`ABSENT_TABLE`: the register may only shrink, an entry
#: that starts resolving here is an error, and an entry named nowhere is a line
#: to delete.
EXTERNAL_TABLE: Final[tuple[str, ...]] = ("tool", "decision-evals", "docs-external-paths")

#: ``pyproject.toml`` table naming paths that are mentioned while deliberately
#: untracked. Same shape and same discipline as :data:`ABSENT_TABLE`.
IGNORED_TABLE: Final[tuple[str, ...]] = ("tool", "decision-evals", "docs-ignored-paths")

#: An inline code span: `` `de check` ``.
_CODE_SPAN: Final = re.compile(r"`([^`\n]+)`")

#: A fenced block, language tag discarded.
_FENCE: Final = re.compile(r"^```[^\n]*\n(.*?)^```", re.MULTILINE | re.DOTALL)

#: ``de check``, including under ``uv run`` / ``python -m uv run``.
_COMMAND: Final = re.compile(r"\bde\s+([a-z][a-z0-9-]*)")

#: ``[text](target)`` -- target captured, angle-bracket form included.
_LINK: Final = re.compile(r"\[[^\]]*\]\(<?([^)\s>]+)>?\)")

#: A row of a markdown table, first cell captured.
_ROW: Final = re.compile(r"^\|\s*([^|]+?)\s*\|", re.MULTILINE)

#: Illustrative rather than literal: ``results/<skill>/<date>-<sha7>/``.
_PLACEHOLDER: Final = re.compile(r"[<>{}*\s]|\.\.\.")


@dataclass(frozen=True)
class DocIssue:
    """One documentation reference that does not resolve."""

    where: str
    message: str

    def __str__(self) -> str:
        return f"{self.where}: {self.message}"


def scanned_files(repo_root: Path) -> list[Path]:
    """Every living documentation file, deduplicated and ordered."""
    seen: dict[Path, None] = {}
    for pattern in SCANNED:
        for path in sorted(repo_root.glob(pattern)):
            if not path.is_file():
                continue
            relative = _relative(path, repo_root)
            if relative in EXCLUDED or relative.startswith(tuple(sorted(EXCLUDED_PREFIXES))):
                continue
            seen.setdefault(path, None)
    return list(seen)


def _relative(path: Path, repo_root: Path) -> str:
    return str(path.relative_to(repo_root)).replace("\\", "/")


def code_fragments(text: str) -> list[str]:
    """Inline code spans and fenced block bodies.

    Both, because ``de check`` is written inline in prose and inside a ``bash``
    fence in the same file, and a check that read only one of them would pass a
    README that was wrong in the other.
    """
    without_fences = _FENCE.sub("\n", text)
    return [*_FENCE.findall(text), *_CODE_SPAN.findall(without_fences)]


def _load_register(repo_root: Path, table: tuple[str, ...]) -> dict[str, str]:
    """One ``pyproject.toml`` table of declaration to reason, or ``{}``.

    Shared by :func:`load_absent_commands`, :func:`load_external_paths` and
    :func:`load_ignored_paths`, which differ only in the table they read. Every
    way of not having the table is tolerated rather than raising: a repository
    without one is the state before anybody declares an exception, and the gate
    has to run there.
    """
    pyproject = repo_root / "pyproject.toml"
    if not pyproject.is_file():
        return {}
    node: object = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    for key in table:
        if not isinstance(node, dict):
            return {}
        node = node.get(key, {})
    if not isinstance(node, dict):
        return {}
    return {str(key): str(value) for key, value in node.items()}


def load_absent_commands(repo_root: Path) -> dict[str, str]:
    """Commands named in the documentation while deliberately not existing.

    ``SCORECARD.md`` has to be able to say that ``de report`` does not exist,
    which is a true sentence containing a false-looking reference. Like
    ``[tool.decision-evals.unwired]`` the register may only shrink, and an
    entry that becomes a real command is itself an error.
    """
    return _load_register(repo_root, ABSENT_TABLE)


def load_external_paths(repo_root: Path) -> dict[str, str]:
    """Backticked paths the documentation names inside another repository.

    The path-shaped twin of :func:`load_absent_commands`, and it exists for the
    same reason: a reference that does not resolve *here* can still be a true
    sentence. See :data:`EXTERNAL_TABLE`.
    """
    return _load_register(repo_root, EXTERNAL_TABLE)


def load_ignored_paths(repo_root: Path) -> dict[str, str]:
    """Paths named in the documentation while deliberately untracked.

    Added 2026-08-19, when the gate was first run against a clean clone instead
    of a working directory and two living documents were found naming files
    that ``.gitignore`` excludes on purpose -- an append-only run checkpoint
    cannot be committed mid-run, so ``results/track-0/`` and
    ``results/triggers/`` are ignored by a stated and correct decision. The
    consequence nobody had noticed is that those references can never resolve
    for anyone who clones this repository, and the gate was right to say so.

    Deleting the sentences would lose real information: the checkpoint exists,
    it is what the surrounding claim rests on, and a reader reproducing the run
    will have it. So the reference stays and the absence is declared, exactly
    as ``de report`` is. The register carries the same two refusals, which is
    what stops it becoming a place to put inconvenient failures: an entry whose
    path exists is an error, and so is an entry named nowhere.
    """
    return _load_register(repo_root, IGNORED_TABLE)


def check_command_references(repo_root: Path, commands: set[str]) -> list[DocIssue]:
    """Every ``de <cmd>`` in the living documentation is a registered command."""
    absent = load_absent_commands(repo_root)
    issues: list[DocIssue] = []
    named: set[str] = set()

    for path in scanned_files(repo_root):
        where = _relative(path, repo_root)
        seen: set[str] = set()
        for fragment in code_fragments(path.read_text(encoding="utf-8")):
            for referenced in sorted(set(_COMMAND.findall(fragment))):
                named.add(referenced)
                if referenced in commands or referenced in absent:
                    continue
                if referenced in seen:
                    continue
                seen.add(referenced)
                issues.append(
                    DocIssue(
                        where,
                        f"`de {referenced}` is not a command. The documentation is the "
                        "install instructions; a command that does not exist is an "
                        "error message the reader gets instead of the tool. Fix the "
                        "reference, or declare it under "
                        "`[tool.decision-evals.docs-absent-commands]` if the point is "
                        "that it does not exist.",
                    )
                )

    for referenced in sorted(absent):
        if referenced in commands:
            issues.append(
                DocIssue(
                    "pyproject.toml",
                    f"`de {referenced}` is declared absent and is now a real command. "
                    "Delete the entry — a note that outlives the situation it "
                    "describes is how the last two dead integrity modules stayed "
                    "invisible.",
                )
            )
        elif referenced not in named:
            issues.append(
                DocIssue(
                    "pyproject.toml",
                    f"`de {referenced}` is declared absent and is named nowhere in the "
                    "documentation. Delete the line.",
                )
            )
    return issues


def link_targets(text: str) -> set[str]:
    """Relative markdown link targets, which resolve against the linking file."""
    return {
        target
        for target in _LINK.findall(_FENCE.sub("\n", text))
        if "://" not in target and not target.startswith(("#", "mailto:"))
    }


def repo_paths(fragments: list[str], top_level: set[str]) -> set[str]:
    """Backticked repository paths, which resolve against the repository root.

    A backticked string is only treated as a path when its first segment is a
    real top-level directory. Without that gate ``decision_evals.triggers`` and
    every prose fragment containing a slash would be resolved as a filename.

    The two bases are not interchangeable, and conflating them is a live bug
    rather than a hypothetical: resolving ``skills/`` against ``docs/`` reports
    every correct path in ``docs/`` as broken, which is what the first run of
    this check did.
    """
    found: set[str] = set()
    for fragment in fragments:
        candidate = fragment.strip()
        if "/" not in candidate or _PLACEHOLDER.search(candidate):
            continue
        if candidate.split("/", 1)[0] in top_level:
            found.add(candidate)
    return found


def check_path_references(repo_root: Path) -> list[DocIssue]:
    """Every relative link and repo path in the living documentation resolves.

    Repo-rooted paths may be excused by :data:`EXTERNAL_TABLE`; markdown links
    may not. A link is an offer to the reader to follow it, and a link into
    another repository is written as a URL rather than a relative path, so an
    unresolvable one is a defect however true the sentence around it is.
    """
    external = load_external_paths(repo_root)
    top_level = {path.name for path in repo_root.iterdir() if path.is_dir()}
    ignored = load_ignored_paths(repo_root)
    issues: list[DocIssue] = []
    named: set[str] = set()

    for path in scanned_files(repo_root):
        where = _relative(path, repo_root)
        text = path.read_text(encoding="utf-8")
        rooted = repo_paths(code_fragments(text), top_level)
        named |= rooted
        candidates = [
            *((reference, path.parent, False) for reference in link_targets(text)),
            *((reference, repo_root, True) for reference in rooted),
        ]
        for reference, base, is_rooted in sorted(candidates, key=lambda item: item[0]):
            if is_rooted and reference in external:
                continue
            # A fragment identifier is not part of the path. Anchor-only links
            # never reach here -- :func:`link_targets` drops them -- so the
            # remainder is always a non-empty path.
            target = reference.split("#", 1)[0]
            named.add(target)
            if (base / target).resolve().exists():
                continue
            if target in ignored:
                continue
            issues.append(
                DocIssue(
                    where,
                    f"`{reference}` does not exist. A link the reader cannot follow is "
                    "the same defect as a command that does not run. Fix the reference, "
                    "or declare it under `[tool.decision-evals.docs-external-paths]` if "
                    "it names a path inside another repository, or under "
                    "`[tool.decision-evals.docs-ignored-paths]` if the point is that "
                    "`.gitignore` excludes it deliberately.",
                )
            )

    # Only the may-only-shrink refusal for the untracked register, and the
    # asymmetry with :data:`EXTERNAL_TABLE` above is deliberate. That register
    # errors on an entry that becomes real, because a path this repository grew
    # is true on every machine. A declared-untracked path *does* exist on the
    # machine that ran the experiment and does not on a clean clone, so
    # existence is not evidence of a stale entry -- refusing on it would put the
    # gate red for the maintainer and green in CI, which is the failure this
    # register was written to fix, inverted.
    for reference in sorted(ignored):
        if reference not in named:
            issues.append(
                DocIssue(
                    "pyproject.toml",
                    f"`{reference}` is declared untracked and is named nowhere in the "
                    "documentation. Delete the line.",
                )
            )

    return [*issues, *_check_external_register(repo_root, external, named)]


def _check_external_register(
    repo_root: Path, external: dict[str, str], named: set[str]
) -> list[DocIssue]:
    """The external-paths register may only shrink, and every line must earn it.

    Both refusals mirror :func:`check_command_references`. An entry that starts
    resolving here is the more interesting of the two: it means the repository
    grew the path it was describing in somebody else's, and the excuse now hides
    a reference the gate should be checking.
    """
    issues: list[DocIssue] = []
    for reference in sorted(external):
        if (repo_root / reference).resolve().exists():
            issues.append(
                DocIssue(
                    "pyproject.toml",
                    f"`{reference}` is declared external and now exists here. Delete "
                    "the entry — an excuse that outlives the situation it describes "
                    "stops a real reference from being checked.",
                )
            )
        elif reference not in named:
            issues.append(
                DocIssue(
                    "pyproject.toml",
                    f"`{reference}` is declared external and is named nowhere in the "
                    "documentation. Delete the line.",
                )
            )
    return issues


def component_entries(repo_root: Path) -> list[str]:
    """Directories named in the README's component table."""
    readme = repo_root / "README.md"
    if not readme.is_file():
        return []
    text = readme.read_text(encoding="utf-8")
    start = text.find(COMPONENT_HEADING)
    if start < 0:
        return []
    end = text.find("\n## ", start + len(COMPONENT_HEADING))
    section = text[start : end if end > 0 else len(text)]

    entries: list[str] = []
    for cell in _ROW.findall(section):
        for span in _CODE_SPAN.findall(cell):
            if span.endswith("/"):
                entries.append(span.rstrip("/"))
    return entries


def check_component_table(repo_root: Path) -> list[DocIssue]:
    """The README's map of the repository agrees with the repository.

    Both directions. A listed component that does not exist sent readers to
    ``preregistration/`` for eight weeks; an existing component that is not
    listed is how ``paper/`` and ``scripts/`` stayed invisible in the only file
    most people read.
    """
    readme = repo_root / "README.md"
    if not readme.is_file():
        return [DocIssue("README.md", "the README is missing")]
    if COMPONENT_HEADING not in readme.read_text(encoding="utf-8"):
        return [
            DocIssue(
                "README.md",
                f"has no `{COMPONENT_HEADING}` section. The component table is what this "
                "check compares against the directory listing; without it the map of the "
                "repository is ungated again.",
            )
        ]

    listed = set(component_entries(repo_root))
    actual = {
        path.name
        for path in repo_root.iterdir()
        if path.is_dir() and not path.name.startswith(".") and path.name not in UNLISTED_DIRS
    }

    issues = [
        DocIssue(
            "README.md",
            f"the component table lists `{name}/`, which is not a directory. This is the "
            "defect the check was written for: `preregistration/` was advertised as "
            "holding hypotheses committed before the run, and has never existed.",
        )
        for name in sorted(listed - actual)
    ]
    issues += [
        DocIssue(
            "README.md",
            f"`{name}/` exists and the component table does not list it. The table is the "
            "map; a directory missing from it is a directory nobody reads.",
        )
        for name in sorted(actual - listed)
    ]
    return issues


def index_entries(repo_root: Path) -> set[str]:
    """File names the documentation index links, as bare ``NAME.md``.

    Targets carrying a slash are dropped: ``../SCORECARD.md`` and
    ``reviews/HOUSE_STYLE.md`` are real links to real files, and neither is a
    row claiming to index ``docs/`` itself.
    """
    index = repo_root / INDEX_PATH
    if not index.is_file():
        return set()
    return {
        target
        for target in link_targets(index.read_text(encoding="utf-8"))
        if "/" not in target and target.endswith(".md")
    }


def linked_paths(repo_root: Path) -> set[Path]:
    """Every existing file the living documentation links to.

    Targets resolve against the linking file's own directory, which is what a
    reader's browser does. Anchors are stripped: a link into a section is a
    link to the file that holds it. No guard against an empty result, because
    :func:`link_targets` has already dropped every target that begins with
    ``#``, and a branch nothing can reach is the defect :mod:`decision_evals.wiring`
    exists to refuse.
    """
    found: set[Path] = set()
    for path in scanned_files(repo_root):
        parent = path.resolve().parent
        for target in link_targets(path.read_text(encoding="utf-8")):
            resolved = (parent / target.split("#", 1)[0]).resolve()
            if resolved.exists():
                found.add(resolved)
    return found


def check_docs_index(repo_root: Path) -> list[DocIssue]:
    """The documentation index agrees with the documentation.

    ``docs/README.md`` is the index a reader meets and the page the site serves
    at ``/docs/``. It listed every file under ``docs/`` because somebody kept
    it that way by hand, which held for nineteen documents and would have held
    until the first one nobody remembered. This is the same two-directional
    comparison :func:`check_component_table` makes for the README's map of the
    repository, one level down.

    Three rules. Every ``docs/*.md`` is a row and every row is a file. Every
    subdirectory of ``docs/`` is named. And every living document inside those
    subdirectories is linked from somewhere, which is the rule that found
    ``docs/superpowers/drafts/s9-ledger-replacement/README.md``: 315 lines
    describing an unshipped procedure, reachable only by listing the directory.
    """
    index = repo_root / INDEX_PATH
    if not index.is_file():
        return [DocIssue(INDEX_PATH, "the documentation index is missing")]

    listed = index_entries(repo_root)
    actual = {path.name for path in (repo_root / "docs").glob("*.md") if path.name != "README.md"}

    issues = [
        DocIssue(
            INDEX_PATH,
            f"the index lists `{name}`, which is not a file under `docs/`. A row pointing "
            "at nothing is the defect `check_component_table` was written for, one level "
            "down.",
        )
        for name in sorted(listed - actual)
    ]
    issues += [
        DocIssue(
            INDEX_PATH,
            f"`docs/{name}` exists and the index does not list it. This page is the map "
            "and the site's `/docs/` landing page; a document missing from it is a "
            "document nobody reads.",
        )
        for name in sorted(actual - listed)
    ]

    named = {
        target.split("/", 1)[0]
        for target in link_targets(index.read_text(encoding="utf-8"))
        if "/" in target and not target.startswith("..")
    }
    issues += [
        DocIssue(
            INDEX_PATH,
            f"`docs/{directory.name}/` exists and the index never names it. A "
            "subdirectory the map does not mention is a wing of the building with no "
            "door.",
        )
        for directory in sorted((repo_root / "docs").iterdir())
        if directory.is_dir() and directory.name not in named
    ]

    linked = linked_paths(repo_root)
    issues += [
        DocIssue(
            _relative(path, repo_root),
            "nothing links to this document. It renders on the site and sits in the "
            "repository, and the only way to arrive at it is to list the directory it "
            "is in.",
        )
        for path in scanned_files(repo_root)
        if _relative(path, repo_root).count("/") > 1
        and _relative(path, repo_root).startswith("docs/")
        and path.resolve() not in linked
    ]
    return issues


def check_audience_lines(repo_root: Path) -> list[DocIssue]:
    """Every living document declares the one audience it serves.

    ``docs/VOICE.md`` names four audiences and says a document serving two
    serves neither. The declaration was a convention, and its stated value was
    that writing the line forces the question -- which it does, for anyone who
    remembers to write it.

    The rule has no exemptions. ``docs/RUN_INDEX.md`` is generated, so
    :func:`decision_evals.provenance.render_index` emits the line rather than
    the register carrying a name somebody has to keep true.
    """
    return [
        DocIssue(
            _relative(path, repo_root),
            f"carries no `{AUDIENCE_MARKER}` line. Name the one audience this document "
            "serves; `docs/DOCUMENTATION_MAP.md` lists the four and what each one wants.",
        )
        for path in scanned_files(repo_root)
        if AUDIENCE_MARKER not in path.read_text(encoding="utf-8")
    ]


def check_docs(repo_root: Path, commands: set[str]) -> list[DocIssue]:
    """Every reference in the living documentation resolves to something real."""
    return [
        *check_command_references(repo_root, commands),
        *check_path_references(repo_root),
        *check_component_table(repo_root),
        *check_docs_index(repo_root),
        *check_audience_lines(repo_root),
    ]


def census(repo_root: Path) -> tuple[int, int, int, int, int]:
    """``(files, components, indexed, commands_absent, paths_external)``."""
    return (
        len(scanned_files(repo_root)),
        len(component_entries(repo_root)),
        len(index_entries(repo_root)),
        len(load_absent_commands(repo_root)),
        len(load_external_paths(repo_root)),
    )
