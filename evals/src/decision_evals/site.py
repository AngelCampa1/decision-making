"""A published site that is not older than the repository it publishes.

The site under ``site/`` renders the markdown in this repository **in place** --
``docs/``, ``notebook/``, ``results/`` and ``skills/`` are read by the build,
not copied into it. That is the property worth having: there is no second copy
of ``STATUS.md`` that can disagree with the first.

It is also the property that creates this gate's problem. A build is a snapshot,
so the moment a document changes the published pages are stale, and a stale page
is indistinguishable from a current one by looking at it. This repository has
already paid for two hand-maintained indexes that drifted -- ``SCORECARD.md``
carries a note about claiming to be generated when it was not, and
``docs/STATUS.md`` says in its own opening line that its summary counts had
fallen behind the tables underneath them.

So the site is treated exactly as :mod:`decision_evals.provenance` treats
``docs/RUN_INDEX.md``: generated by a command, and refused by ``de check`` when
what is committed does not match what the tree would produce.

**What this cannot catch, stated so nobody mistakes green for correct.** It
proves the site was *built* from the current tree. It does not prove anybody is
serving that build. ``de check`` is offline and deterministic by design, so it
cannot look at the live site; a green gate beside a page nobody is serving is
exactly as green as a deployed one.

**That gap used to be carried by a person, and on 2026-08-19 it was dropped
twice in one morning.** Publishing was ``de site --deploy``, which force-pushed
whatever local ``HEAD`` happened to be to a ``gh-pages`` branch. Once it
published a build of a work-in-progress commit from a feature branch, caught by
hand nine minutes later. Separately the published branch sat 43 minutes and one
commit behind ``main`` with nothing to say so. Earlier in the same week the gap
had turned out to be wider still: Pages was configured
``source: {branch: main, path: /docs}``, so for six days the served site was a
hand-written ``docs/index.html`` and nothing here had ever reached it, while
``de site --deploy`` printed *published* and this check reported the manifest
current. Both were true. Neither asks what the host serves.

**Publishing is no longer a thing anybody remembers to do.**
``.github/workflows/deploy-site.yml`` builds and deploys on push to ``main``,
and the Pages source is that workflow. No local publish command is left, and the
``gh-pages`` branch it pushed to is retired. So the build reaching the world is
now a property of ``main`` rather than of a person.

What remains outside this module is unchanged and is still worth stating: this
gate is offline, so it cannot see the live page, and it never will.
:mod:`decision_evals.deployed` answers that on demand, by fetching what the
deployed site records about its own origin. It is a separate command on purpose
— a gate step that can fail because a CDN is slow is a step people learn to
ignore.

The same standing limitation is registered for :mod:`decision_evals.docs`,
:mod:`decision_evals.provenance` and :mod:`decision_evals.wiring`.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Final

#: The site project. Everything it needs lives under here, including
#: ``package.json`` -- so ``node_modules/`` and ``dist/`` nest inside it rather
#: than appearing at the repository root, where they would be unlisted
#: top-level directories and fail ``docs.check_component_table``.
SITE_DIR: Final = "site"

#: The globs the site renders and the files that decide how.
#:
#: Three readers, one declaration: this module hashes ``hash`` and ``site`` to
#: gate staleness, ``site/src/content.config.ts`` loads ``base`` and
#: ``pattern``, and ``site/src/lib/remark-rewrite-links.mjs`` turns ``prefix``
#: into ``route``. All three import this file.
#:
#: They did not, until 2026-08-21. Each restated the globs and a comment asked
#: the next author to keep them in step, which is the mechanism this repository
#: keeps finding at the scene. An adversarial review checked the comment that
#: claimed otherwise and found two live drifts: ``*.md`` against an explicit
#: list of four root documents, and ``plugin/skills/README.md`` hashed as a
#: rendered input against no collection and no route, so a change to it staled
#: a build that had never published it.
#:
#: The file is not in ``pyproject.toml`` because TypeScript cannot read TOML
#: without another dependency.
INPUTS_PATH: Final = "site/inputs.json"

#: The committed record of what the last build was built from.
MANIFEST_PATH: Final = "site/build-manifest.json"

_NOTE: Final = (
    "Generated by `de site`. Do not edit. Records a hash of every file the site "
    "renders, so `de check` can refuse a published build that is older than its "
    "inputs. It proves the site was built, never that anybody is serving it -- "
    "`de deployed` answers that, and the module docstring of "
    "decision_evals.site says why the two are separate."
)


@dataclass(frozen=True)
class SiteIssue:
    """One reason the committed build cannot be trusted."""

    where: str
    message: str

    def __str__(self) -> str:
        return f"{self.where}: {self.message}"


def site_present(repo_root: Path) -> bool:
    """Whether there is a site to gate at all.

    The gate ships before the site does, so that the commit adding ``site/`` is
    the commit its manifest first appears in. Until then every check here is a
    no-op rather than a failure.
    """
    return (repo_root / SITE_DIR).is_dir()


def load_inputs(repo_root: Path) -> list[str]:
    """The globs the site renders, in the order they are declared.

    A collection's ``hash`` is what this module reads, and it is allowed to be
    wider than the ``pattern`` Astro loads: ``CLAUDE.md`` is hashed and not
    rendered, because a mirror that moves without a rebuild is a published page
    that disagrees with the repository.
    """
    path = repo_root / INPUTS_PATH
    if not path.is_file():
        return []
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return []
    if not isinstance(data, dict):
        return []

    patterns: list[str] = []
    collections = data.get("collections", [])
    if isinstance(collections, list):
        for entry in collections:
            if not isinstance(entry, dict):
                continue
            hashed = entry.get("hash", [])
            if isinstance(hashed, list):
                patterns.extend(str(item) for item in hashed)
    section = data.get("site", [])
    if isinstance(section, list):
        patterns.extend(str(item) for item in section)
    return patterns


def input_files(repo_root: Path) -> list[Path]:
    """Every file the site renders or is built by, deduplicated and sorted.

    Directories are skipped rather than hashed, and the build's own output is
    never an input -- hashing ``dist/`` would make the manifest a record of
    itself.
    """
    seen: dict[Path, None] = {}
    for pattern in load_inputs(repo_root):
        for path in repo_root.glob(pattern):
            if not path.is_file():
                continue
            if any(
                part in {"node_modules", "dist", ".astro", ".astro-cache"} for part in path.parts
            ):
                continue
            seen.setdefault(path, None)
    return sorted(seen, key=lambda p: _relative(p, repo_root))


def _relative(path: Path, repo_root: Path) -> str:
    return str(path.relative_to(repo_root)).replace("\\", "/")


def _digest(path: Path) -> str:
    """SHA-256 of the file's content with line endings normalised.

    Without the normalisation a Windows checkout and a Linux one disagree about
    identical content, and the gate would fail for whichever machine did not
    build last.
    """
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def render_manifest(repo_root: Path) -> str:
    """What the manifest should say about the tree as it stands."""
    inputs = {_relative(path, repo_root): _digest(path) for path in input_files(repo_root)}
    payload = {
        "generated_by": "de site",
        "note": _NOTE,
        "inputs": inputs,
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def _committed(repo_root: Path) -> dict[str, str]:
    path = repo_root / MANIFEST_PATH
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}
    inputs = data.get("inputs") if isinstance(data, dict) else None
    if not isinstance(inputs, dict):
        return {}
    return {str(key): str(value) for key, value in inputs.items()}


def changed_inputs(repo_root: Path) -> list[str]:
    """Files that differ from what the committed build was built from.

    Per-file rather than one aggregate digest, so the refusal can name what
    moved. A gate that says only "something changed" is a gate people stop
    reading.
    """
    current = {_relative(path, repo_root): _digest(path) for path in input_files(repo_root)}
    committed = _committed(repo_root)
    return sorted(
        set(current) ^ set(committed)
        | {name for name, digest in current.items() if committed.get(name, digest) != digest}
    )


def manifest_is_current(repo_root: Path) -> bool:
    """Whether the committed manifest matches what the tree would generate."""
    path = repo_root / MANIFEST_PATH
    if not path.is_file():
        return False
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") == render_manifest(repo_root)


#: What one collection has to declare, and which reader would go quiet without
#: it. ``prefix`` and ``route`` are absent from this list because a collection
#: may legitimately have neither -- root documents share no prefix and are
#: routed one at a time -- but they travel together, which is checked below.
_COLLECTION_FIELDS: Final[tuple[tuple[str, str], ...]] = (
    ("name", "site/src/content.config.ts, which asks for a collection by name"),
    ("base", "site/src/content.config.ts, which passes it to Astro's loader"),
    ("pattern", "site/src/content.config.ts, which passes it to Astro's loader"),
    ("hash", "this module, which hashes it to decide whether a build is stale"),
)


def collection_issues(repo_root: Path) -> list[SiteIssue]:
    """Every collection declares what all three of its readers need.

    The point of one declaration with three readers is that a collection cannot
    be added to one and forgotten in another. That only holds if a missing field
    is an error: without this, a collection with no ``hash`` renders happily and
    is never hashed, which is the ``plugin/skills/README.md`` failure in the
    other direction and just as quiet.
    """
    path = repo_root / INPUTS_PATH
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        return [
            SiteIssue(
                INPUTS_PATH,
                f"is not parseable JSON ({error.msg}, line {error.lineno}). Three "
                "readers load this file, and a truncated write reads to all of them "
                "as a site that renders nothing.",
            )
        ]

    collections = data.get("collections") if isinstance(data, dict) else None
    if not isinstance(collections, list):
        return [
            SiteIssue(
                INPUTS_PATH,
                "has no `collections` array. It is what content.config.ts loads, what "
                "remark-rewrite-links.mjs routes from, and what this module hashes.",
            )
        ]

    issues: list[SiteIssue] = []
    for index, entry in enumerate(collections):
        where = f"{INPUTS_PATH} collection {index}"
        if not isinstance(entry, dict):
            issues.append(SiteIssue(where, "is not an object."))
            continue
        name = entry.get("name")
        if isinstance(name, str):
            where = f"{INPUTS_PATH} collection `{name}`"
        issues += [
            SiteIssue(where, f"declares no `{field}`, which is read by {reader}.")
            for field, reader in _COLLECTION_FIELDS
            if not entry.get(field)
        ]
        if bool(entry.get("prefix")) != bool(entry.get("route")):
            issues.append(
                SiteIssue(
                    where,
                    "declares one of `prefix` and `route` and not the other. A prefix "
                    "with no route sends every link into it off-site, and a route with "
                    "no prefix is a page nothing links to.",
                )
            )
    return issues


def check_site(repo_root: Path) -> list[SiteIssue]:
    """Refuse a tree whose published site is older than what it publishes."""
    if not site_present(repo_root):
        return []

    if not (repo_root / INPUTS_PATH).is_file():
        return [
            SiteIssue(
                INPUTS_PATH,
                "is missing. It is the one list of what the site renders, read by "
                "both this gate and site/src/content.config.ts, so without it the "
                "build and the check are guessing at different sets of files.",
            )
        ]

    malformed = collection_issues(repo_root)
    if malformed:
        return malformed

    if not load_inputs(repo_root):
        return [
            SiteIssue(
                INPUTS_PATH,
                "declares no inputs. A manifest over nothing is current by "
                "construction and would report green for any site at all.",
            )
        ]

    if not (repo_root / MANIFEST_PATH).is_file():
        return [
            SiteIssue(
                MANIFEST_PATH,
                "is missing. Run `de site`. Without it nothing records which "
                "version of these documents the published pages were built from.",
            )
        ]

    if manifest_is_current(repo_root):
        return []

    changed = changed_inputs(repo_root)
    shown = "\n".join(f"      {name}" for name in changed[:10])
    if len(changed) > 10:
        shown += f"\n      ... and {len(changed) - 10} more"
    return [
        SiteIssue(
            MANIFEST_PATH,
            f"is stale. {len(changed)} input(s) changed since the site was last "
            "built. Run `de site`. The site renders these files rather than "
            "copies of them, so a document that changes without a rebuild is a "
            "published page that disagrees with the repository until somebody "
            f"notices.\n{shown}",
        )
    ]


def census(repo_root: Path) -> tuple[int, int]:
    """``(input_files, changed_since_last_build)``."""
    if not site_present(repo_root):
        return (0, 0)
    return (len(input_files(repo_root)), len(changed_inputs(repo_root)))
